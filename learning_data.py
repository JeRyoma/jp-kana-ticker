def parse_words(text: str, script: str) -> dict[str, dict]:
    out = {}
    for row in text.strip().splitlines():
        spelling, reading, meaning, emoji = row.strip().split("|")
        if spelling in out:
            raise ValueError(f"duplicate {script}: {spelling}")
        out[spelling] = {"value": spelling, "reading": reading, "meaning": meaning,
                         "emoji": emoji, "script": script}
    return out

